package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

type blockEntry struct {
	ID           int              `json:"id"`
	Name         string           `json:"name"`
	MinStateID   int              `json:"minStateId"`
	MaxStateID   int              `json:"maxStateId"`
	Material     string           `json:"material,omitempty"`
	HarvestTools map[string]bool  `json:"harvestTools,omitempty"`
}

type itemEntry struct {
	ID   int    `json:"id"`
	Name string `json:"name"`
}

type foodEntry struct {
	ID   int    `json:"id"`
	Name string `json:"name"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	base := "../.."

	if err := genBlocks(base); err != nil {
		return err
	}
	if err := genItems(base); err != nil {
		return err
	}
	if err := genFoods(base); err != nil {
		return err
	}
	return nil
}

func genBlocks(base string) error {
	blocks, err := loadBlocks(base + "/data/blocks.json")
	if err != nil {
		return err
	}

	toolItemIDs := map[string]string{
		"819": "wooden_axe", "820": "wooden_pickaxe", "821": "wooden_shovel", "822": "wooden_hoe", "823": "wooden_sword",
		"824": "stone_axe", "825": "stone_pickaxe", "826": "stone_shovel", "827": "stone_hoe", "828": "stone_sword",
		"829": "iron_axe", "830": "iron_pickaxe", "831": "iron_shovel", "832": "iron_hoe", "833": "iron_sword",
		"834": "golden_axe", "835": "golden_pickaxe", "836": "golden_shovel", "837": "golden_hoe", "838": "golden_sword",
		"839": "diamond_axe", "840": "diamond_pickaxe", "841": "diamond_shovel", "842": "diamond_hoe", "843": "diamond_sword",
		"844": "netherite_axe", "845": "netherite_pickaxe", "846": "netherite_shovel", "847": "netherite_hoe", "848": "netherite_sword",
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by data/gen; DO NOT EDIT.\n\npackage registry\n\n")
	sb.WriteString("var stateIDToName = map[uint32]string{\n")

	type entry struct {
		stateID int
		name    string
	}
	var entries []entry
	for _, b := range blocks {
		for s := b.MinStateID; s <= b.MaxStateID; s++ {
			entries = append(entries, entry{stateID: s, name: b.Name})
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].stateID < entries[j].stateID })

	for _, e := range entries {
		sb.WriteString(fmt.Sprintf("\t%d: \"%s\",\n", e.stateID, e.name))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("var stateIDToTool = map[uint32]string{\n")

	woodenToolByMaterial := map[string]string{
		"mineable/axe":    "wooden_axe",
		"mineable/pickaxe": "wooden_pickaxe",
		"mineable/shovel":  "wooden_shovel",
		"mineable/hoe":     "wooden_hoe",
	}

	tierOrder := []string{"wooden_", "stone_", "iron_", "golden_", "diamond_", "netherite_"}
	toolTypes := []string{"axe", "pickaxe", "shovel", "hoe", "sword"}

	for _, b := range blocks {
		var best string

		if len(b.HarvestTools) > 0 {
			for _, tier := range tierOrder {
				for _, tt := range toolTypes {
					toolName := tier + tt
					for toolID, name := range toolItemIDs {
						if name == toolName && b.HarvestTools[toolID] {
							best = toolName
							goto found
						}
					}
				}
			}
		found:
		}

		if best == "" {
			best = woodenToolByMaterial[b.Material]
		}

		if best == "" {
			continue
		}

		for state := b.MinStateID; state <= b.MaxStateID; state++ {
			sb.WriteString(fmt.Sprintf("\t%d: \"%s\",\n", state, best))
		}
	}
	sb.WriteString("}\n\n")

	sb.WriteString(`func BlockName(stateID uint32) (string, bool) {
	name, ok := stateIDToName[stateID]
	return name, ok
}

func BestToolFor(stateID uint32) (string, bool) {
	tool, ok := stateIDToTool[stateID]
	return tool, ok
}
`)

	return os.WriteFile(base+"/orchestrator/internal/mc_protocol/registry/blocks.go", []byte(sb.String()), 0644)
}

func genItems(base string) error {
	raw, err := os.ReadFile(base + "/data/items.json")
	if err != nil {
		return err
	}

	var items []itemEntry
	if err := json.Unmarshal(raw, &items); err != nil {
		return err
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by data/gen; DO NOT EDIT.\n\npackage registry\n\n")
	sb.WriteString("var itemIDToName = map[int32]string{\n")
	for _, item := range items {
		sb.WriteString(fmt.Sprintf("\t%d: \"%s\",\n", item.ID, item.Name))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("var itemNameToID = map[string]int32{\n")
	for _, item := range items {
		sb.WriteString(fmt.Sprintf("\t\"%s\": %d,\n", item.Name, item.ID))
	}
	sb.WriteString("}\n\n")

	sb.WriteString(`func ItemName(id int32) (string, bool) {
	name, ok := itemIDToName[id]
	return name, ok
}

func ItemID(name string) (int32, bool) {
	id, ok := itemNameToID[name]
	return id, ok
}
`)

	return os.WriteFile(base+"/orchestrator/internal/mc_protocol/registry/items.go", []byte(sb.String()), 0644)
}

func genFoods(base string) error {
	raw, err := os.ReadFile(base + "/data/foods.json")
	if err != nil {
		return err
	}

	var foods []foodEntry
	if err := json.Unmarshal(raw, &foods); err != nil {
		return err
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by data/gen; DO NOT EDIT.\n\npackage registry\n\n")
	sb.WriteString("var foodItemIDs = map[int32]bool{\n")
	for _, f := range foods {
		sb.WriteString(fmt.Sprintf("\t%d: true,\n", f.ID))
	}
	sb.WriteString("}\n\n")

	sb.WriteString(`func IsFoodItem(id int32) bool {
	return foodItemIDs[id]
}
`)

	return os.WriteFile(base+"/orchestrator/internal/mc_protocol/registry/foods.go", []byte(sb.String()), 0644)
}

func loadBlocks(path string) ([]blockEntry, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var blocks []blockEntry
	if err := json.Unmarshal(raw, &blocks); err != nil {
		return nil, err
	}
	return blocks, nil
}

func loadItemNames(path string) ([]itemEntry, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var items []itemEntry
	if err := json.Unmarshal(raw, &items); err != nil {
		return nil, err
	}
	return items, nil
}
